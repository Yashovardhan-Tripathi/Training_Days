mylist=[ 2 , 4 , 6 , 8 , 9 , 1 , 5 ] 
#        0   1   2   3   4   5   6
#       -7  -6  -5  -4  -3  -2  -1
#slicing of List
print(mylist[0])#2
print(mylist[5])#1
print(mylist[1:])#[4 , 6 , 8 , 9 , 1 , 5]
print(mylist[1:3])#[4 , 6]
print(mylist[-1])#[5]
print(mylist[0:6:2])#[2 , 6 , 9]
print(mylist[::-1])#[5 , 1 , 9 , 8 , 6 , 4 , 2]
print(mylist[::1])#[2 , 4 , 6 , 8 , 9 , 1 , 5]

